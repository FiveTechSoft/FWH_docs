document.addEventListener("DOMContentLoaded", function() {
  var lang = (window.location.pathname.match(/\/(en|es|pt)\//) || [])[1] || 'en';
  document.querySelectorAll('.index-columns li').forEach(function(li) {
    var cls = li.textContent.trim().toLowerCase();
    if (classLinks[cls]) {
      var a = document.createElement('a');
      a.href = '../../' + lang + '/' + classLinks[cls];
      a.textContent = li.textContent.trim();
      li.textContent = '';
      li.appendChild(a);
    }
  });
});
